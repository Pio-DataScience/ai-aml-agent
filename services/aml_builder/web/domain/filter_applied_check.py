"""Conservative A-side verification that generated SQL applies resolved filters."""

from __future__ import annotations

from typing import Any

import sqlglot
from sqlglot import exp


def check_filter_application(
    sql: str,
    resolved_filters: list[dict[str, Any]],
    *,
    unverifiable: str = "warn",
    transaction_scope: str | None = None,
) -> dict[str, Any]:
    """Check generated predicates against resolved filter values.

    Args:
        sql: SQL generated by Service B.
        resolved_filters: Catalog-resolved filters from the confirmed intent.
        unverifiable: Whether present but unextractable predicates fail or warn.
        transaction_scope: Explicit transaction type scope, including ALL/ANY.

    Returns:
        Per-filter statuses and the deployment-gating validation result.
    """
    checked = []
    for item in resolved_filters:
        if item.get("dimension") == "explanation_code" and str(
            transaction_scope or ""
        ).casefold() in {"all", "any"}:
            continue
        checked.append(item)
    try:
        expressions = sqlglot.parse(sql, read="oracle")
    except (sqlglot.errors.ParseError, ValueError):
        results = [
            _result(item, "unverified", "SQL could not be parsed") for item in checked
        ]
        return _summary(results, unverifiable)

    results: list[dict[str, Any]] = []
    for item in checked:
        predicates = _matching_predicates(expressions, item)
        if not predicates:
            results.append(
                _result(item, "missing", "Target column is absent from a predicate")
            )
            continue
        extracted = [_extract_predicate(predicate, item) for predicate in predicates]
        if any(value is None for value in extracted):
            results.append(
                _result(item, "unverified", "Predicate values could not be extracted")
            )
            continue
        expected = {str(value).strip().casefold() for value in item.get("values", [])}
        valid = all(
            values == expected and polarity == _polarity(item)
            for values, polarity in extracted
        )
        results.append(
            _result(
                item,
                "applied" if valid else "mismatch",
                None if valid else "Predicate polarity or value set differs",
            )
        )
    return _summary(results, unverifiable)


def _matching_predicates(expressions: list[Any], item: dict[str, Any]) -> list[Any]:
    target = item.get("target") or {}
    target_table = str(target.get("table") or "").casefold()
    target_column = str(target.get("column") or "").casefold()
    aliases: dict[str, str] = {}
    for root in expressions:
        for table in root.find_all(exp.Table):
            aliases[table.alias.casefold()] = table.name.casefold()
    found = []
    for root in expressions:
        for predicate in root.find_all(exp.Predicate):
            columns = list(predicate.find_all(exp.Column))
            if isinstance(predicate.this, exp.Column):
                columns.insert(0, predicate.this)
            matching = [
                column for column in columns if column.name.casefold() == target_column
            ]
            if not matching:
                continue
            if target_table and any(
                column.table
                and aliases.get(column.table.casefold(), column.table.casefold())
                != target_table
                for column in matching
            ):
                continue
            found.append(predicate)
    return found


def _extract_predicate(
    predicate: Any, item: dict[str, Any]
) -> tuple[set[str], str] | None:
    negative = False
    if isinstance(predicate, exp.In):
        negative = bool(predicate.args.get("not"))
        parent = predicate.parent
        while isinstance(parent, (exp.Paren, exp.Not)):
            if isinstance(parent, exp.Not):
                negative = not negative
            parent = parent.parent
        if predicate.args.get("query") is not None:
            return None
        values = predicate.expressions
    elif isinstance(predicate, exp.NEQ):
        negative = True
        values = [
            (
                predicate.expression
                if isinstance(predicate.this, exp.Column)
                else predicate.this
            )
        ]
    elif isinstance(predicate, exp.EQ):
        values = [
            (
                predicate.expression
                if isinstance(predicate.this, exp.Column)
                else predicate.this
            )
        ]
    else:
        return None
    if not isinstance(predicate.this, exp.Column) and not (
        isinstance(predicate, (exp.EQ, exp.NEQ))
        and isinstance(predicate.expression, exp.Column)
    ):
        return None
    extracted = set()
    for value in values:
        if not isinstance(value, exp.Literal):
            return None
        extracted.add(str(value.this).strip().casefold())
    if negative and not item.get("polarity_allowed"):
        return extracted, "forbidden_negative"
    return extracted, "negative" if negative else "positive"


def _polarity(item: dict[str, Any]) -> str:
    return (
        "negative"
        if str(item.get("polarity", "positive")).casefold() == "negative"
        else "positive"
    )


def _result(item: dict[str, Any], status: str, detail: str | None) -> dict[str, Any]:
    result = {key: item.get(key) for key in ("dimension", "raw_mention", "polarity")}
    result["status"] = status
    if detail:
        result["detail"] = detail
    return result


def _summary(results: list[dict[str, Any]], unverifiable: str) -> dict[str, Any]:
    failed = any(item["status"] in {"missing", "mismatch"} for item in results)
    failed = failed or (
        unverifiable == "fail"
        and any(item["status"] == "unverified" for item in results)
    )
    return {"validation_success": not failed, "filters": results}
