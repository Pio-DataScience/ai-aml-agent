-- Owner-reviewed Oracle DDL for the Service A development registry.
-- Creates new agent-owned tables; does not rename, alter, or copy either
-- existing PIO_AML_SCENARIO or PIO_AML_PRODUCTION_SCENARIOS table.
-- Review in TOAD before running. The application embeds create-if-missing DDL.

CREATE TABLE PIO_AML_AGENT_PRODUCTION_SCENARIOS (
    SCENARIO_ID VARCHAR2(50) PRIMARY KEY,
    SCENARIO_KEY VARCHAR2(50) NOT NULL,
    VERSION_NO NUMBER NOT NULL,
    PARENT_SCENARIO_ID VARCHAR2(50),
    STATUS VARCHAR2(20) NOT NULL,
    IS_ACTIVE NUMBER(1) NOT NULL,
    THREAD_ID VARCHAR2(200) NOT NULL,
    REVISION_ID VARCHAR2(64) NOT NULL,
    REV_NO NUMBER NOT NULL,
    SIGNATURE_HASH VARCHAR2(64),
    PARAMS_HASH VARCHAR2(64), PLAN_HASH VARCHAR2(64), SQL_HASH VARCHAR2(64),
    METADATA_HASH VARCHAR2(64),
    SIGNATURE_JSON CLOB, PARAMS_JSON CLOB, FILTERS_JSON CLOB,
    METADATA_JSON CLOB, RECEIPT_JSON CLOB, CHANGE_REASON VARCHAR2(500),
    SCENARIO_NAME VARCHAR2(250) NOT NULL,
    SCENARIO_TYPE VARCHAR2(50) NOT NULL,
    DETECTION_LOGIC CLOB, RAW_SQL CLOB NOT NULL,
    TIME_WINDOW_DAYS NUMBER,
    CREATED_BY VARCHAR2(100), CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    UPDATED_BY VARCHAR2(100), UPDATED_AT TIMESTAMP
);

CREATE TABLE PIO_AML_AGENT_SCENARIOS (
    COUNTRY_CODE NUMBER NOT NULL, INST_CODE NUMBER NOT NULL,
    SCENARIO_CODE VARCHAR2(40) NOT NULL,
    SCENARIO_DES_ENG VARCHAR2(400), SCENARIO_DES_NAT_LAN VARCHAR2(400),
    ACTIVE_FLAG VARCHAR2(1) DEFAULT '1', RUN_FLAG VARCHAR2(1) DEFAULT '1',
    VIOLATION_LEVEL VARCHAR2(1), DEGREE_RISK_FLAG VARCHAR2(1),
    CREATED_BY NUMBER, CREATED_DATE DATE DEFAULT SYSDATE,
    UPDATED_BY NUMBER, UPDATED_DATE DATE,
    CATEGORY_CODE VARCHAR2(10), SCE_TYPE_CODE VARCHAR2(10), CLASS_CODE VARCHAR2(10),
    CONSTRAINT PIO_AML_AGENT_SCENARIOS_PK
        PRIMARY KEY (COUNTRY_CODE, INST_CODE, SCENARIO_CODE)
);

CREATE TABLE PIO_AML_AGENT_SCENARIO_AUDIT (
    AUDIT_ID VARCHAR2(64) PRIMARY KEY,
    SCENARIO_ID VARCHAR2(50) NOT NULL, SCENARIO_KEY VARCHAR2(50) NOT NULL,
    ACTION VARCHAR2(30) NOT NULL, ACTOR VARCHAR2(100), ACTOR_ROLE VARCHAR2(30),
    TS TIMESTAMP DEFAULT SYSTIMESTAMP, FROM_STATUS VARCHAR2(20),
    TO_STATUS VARCHAR2(20), REASON VARCHAR2(500), DIFF_JSON CLOB
);

CREATE TABLE PIO_AML_AGENT_SCHEMA_VERSION (
    COMPONENT VARCHAR2(100) PRIMARY KEY,
    VERSION NUMBER NOT NULL,
    APPLIED_AT TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE UNIQUE INDEX PIO_AML_AGENT_PROD_UQ_KEY_VERSION
    ON PIO_AML_AGENT_PRODUCTION_SCENARIOS (SCENARIO_KEY, VERSION_NO);
CREATE UNIQUE INDEX PIO_AML_AGENT_PROD_UQ_THREAD
    ON PIO_AML_AGENT_PRODUCTION_SCENARIOS (THREAD_ID);
CREATE UNIQUE INDEX PIO_AML_AGENT_PROD_UQ_ACTIVE_SIG
    ON PIO_AML_AGENT_PRODUCTION_SCENARIOS
       (CASE WHEN STATUS = 'ACTIVE' THEN SIGNATURE_HASH END);
CREATE INDEX PIO_AML_AGENT_PROD_IX_KEY_STATUS
    ON PIO_AML_AGENT_PRODUCTION_SCENARIOS (SCENARIO_KEY, STATUS);

INSERT INTO PIO_AML_AGENT_SCHEMA_VERSION (COMPONENT, VERSION, APPLIED_AT)
VALUES ('scenario_registry', 2, SYSTIMESTAMP);
