-- P0 legacy review runbook. Owner-run in TOAD; every statement is read-only.
-- Set OWNER to the Oracle schema that owns the Service A registry tables.

-- Count legacy production scenarios and list the exact IDs in scope.
SELECT COUNT(*) AS legacy_prd_count
FROM PIO_AML_PRODUCTION_SCENARIOS
WHERE SUBSTR(SCENARIO_ID, 1, 4) = 'PRD_';

SELECT SCENARIO_ID, SCENARIO_NAME, SCENARIO_TYPE, IS_ACTIVE, CREATED_AT
FROM PIO_AML_PRODUCTION_SCENARIOS
WHERE SUBSTR(SCENARIO_ID, 1, 4) = 'PRD_'
ORDER BY SCENARIO_ID;

-- These production rows are outside scope and must not be touched.
SELECT SCENARIO_ID, SCENARIO_NAME
FROM PIO_AML_PRODUCTION_SCENARIOS
WHERE SUBSTR(SCENARIO_ID, 1, 4) <> 'PRD_'
   OR SCENARIO_ID IS NULL
ORDER BY SCENARIO_ID;

-- Only shared governance rows whose SCENARIO_CODE equals one of the IDs above.
SELECT COUNT(*) AS matching_metadata_count
FROM PIO_AML_SCENARIO s
WHERE EXISTS (
  SELECT 1 FROM PIO_AML_PRODUCTION_SCENARIOS p
  WHERE SUBSTR(p.SCENARIO_ID, 1, 4) = 'PRD_'
    AND p.SCENARIO_ID = s.SCENARIO_CODE
);

SELECT s.*
FROM PIO_AML_SCENARIO s
WHERE EXISTS (
  SELECT 1 FROM PIO_AML_PRODUCTION_SCENARIOS p
  WHERE SUBSTR(p.SCENARIO_ID, 1, 4) = 'PRD_'
    AND p.SCENARIO_ID = s.SCENARIO_CODE
)
ORDER BY s.COUNTRY_CODE, s.INST_CODE, s.SCENARIO_CODE;

-- Known alert references; review row counts before proceeding.
SELECT AML_SCENARIO_CODE, COUNT(*) AS alert_header_rows
FROM PIO_AML_CUSTOMERS
WHERE AML_SCENARIO_CODE IN (
  SELECT SCENARIO_ID FROM PIO_AML_PRODUCTION_SCENARIOS
  WHERE SUBSTR(SCENARIO_ID, 1, 4) = 'PRD_'
)
GROUP BY AML_SCENARIO_CODE
ORDER BY AML_SCENARIO_CODE;

SELECT AML_SCENARIO_CODE, COUNT(*) AS alert_detail_rows
FROM PIO_AML_CUSTOMERS_DET
WHERE AML_SCENARIO_CODE IN (
  SELECT SCENARIO_ID FROM PIO_AML_PRODUCTION_SCENARIOS
  WHERE SUBSTR(SCENARIO_ID, 1, 4) = 'PRD_'
)
GROUP BY AML_SCENARIO_CODE
ORDER BY AML_SCENARIO_CODE;

-- Foreign keys and child tables referencing either registry table.
SELECT c.OWNER, c.TABLE_NAME AS CHILD_TABLE, c.CONSTRAINT_NAME,
       c.R_CONSTRAINT_NAME, p.TABLE_NAME AS PARENT_TABLE, c.DELETE_RULE
FROM ALL_CONSTRAINTS c
JOIN ALL_CONSTRAINTS p
  ON p.OWNER = c.R_OWNER AND p.CONSTRAINT_NAME = c.R_CONSTRAINT_NAME
WHERE c.CONSTRAINT_TYPE = 'R'
  AND p.OWNER = UPPER('&OWNER')
  AND p.TABLE_NAME IN ('PIO_AML_PRODUCTION_SCENARIOS', 'PIO_AML_SCENARIO')
ORDER BY p.TABLE_NAME, c.OWNER, c.TABLE_NAME;

SELECT cc.OWNER, cc.TABLE_NAME, cc.CONSTRAINT_NAME, cc.COLUMN_NAME,
       cc.POSITION, c.R_OWNER, c.R_CONSTRAINT_NAME
FROM ALL_CONS_COLUMNS cc
JOIN ALL_CONSTRAINTS c
  ON c.OWNER = cc.OWNER AND c.CONSTRAINT_NAME = cc.CONSTRAINT_NAME
WHERE c.CONSTRAINT_TYPE = 'R'
  AND c.R_OWNER = UPPER('&OWNER')
  AND c.R_CONSTRAINT_NAME IN (
    SELECT CONSTRAINT_NAME FROM ALL_CONSTRAINTS
    WHERE OWNER = UPPER('&OWNER')
      AND TABLE_NAME IN ('PIO_AML_PRODUCTION_SCENARIOS', 'PIO_AML_SCENARIO')
      AND CONSTRAINT_TYPE IN ('P', 'U')
  )
ORDER BY cc.OWNER, cc.TABLE_NAME, cc.CONSTRAINT_NAME, cc.POSITION;

-- Triggers attached to the two tables.
SELECT OWNER, TRIGGER_NAME, TABLE_OWNER, TABLE_NAME, STATUS, TRIGGERING_EVENT
FROM ALL_TRIGGERS
WHERE TABLE_OWNER = UPPER('&OWNER')
  AND TABLE_NAME IN ('PIO_AML_PRODUCTION_SCENARIOS', 'PIO_AML_SCENARIO')
ORDER BY TABLE_NAME, TRIGGER_NAME;
