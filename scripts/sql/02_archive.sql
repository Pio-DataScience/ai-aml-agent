-- P0 archive runbook. Owner-run in TOAD after reviewing 01_check.sql.
-- Replace YYYYMMDD with one consistent date suffix before running.
-- CTAS backups are limited to PRD_ production IDs and exact matching rows.
-- Oracle DDL commits implicitly; run this before any removal and verify tables.

CREATE TABLE PIO_PROD_BAK_YYYYMMDD AS
SELECT p.* FROM PIO_AML_PRODUCTION_SCENARIOS p
WHERE SUBSTR(p.SCENARIO_ID, 1, 4) = 'PRD_';

CREATE TABLE PIO_SCEN_BAK_YYYYMMDD AS
SELECT s.* FROM PIO_AML_SCENARIO s
WHERE EXISTS (
  SELECT 1 FROM PIO_AML_PRODUCTION_SCENARIOS p
  WHERE SUBSTR(p.SCENARIO_ID, 1, 4) = 'PRD_'
    AND p.SCENARIO_ID = s.SCENARIO_CODE
);

CREATE TABLE PIO_CUST_BAK_YYYYMMDD AS
SELECT c.* FROM PIO_AML_CUSTOMERS c
WHERE c.AML_SCENARIO_CODE IN (
  SELECT SCENARIO_ID FROM PIO_AML_PRODUCTION_SCENARIOS
  WHERE SUBSTR(SCENARIO_ID, 1, 4) = 'PRD_'
);

CREATE TABLE PIO_CDET_BAK_YYYYMMDD AS
SELECT d.* FROM PIO_AML_CUSTOMERS_DET d
WHERE d.AML_SCENARIO_CODE IN (
  SELECT SCENARIO_ID FROM PIO_AML_PRODUCTION_SCENARIOS
  WHERE SUBSTR(SCENARIO_ID, 1, 4) = 'PRD_'
);

-- Verify backup counts against 01_check.sql before exporting/removing.
SELECT COUNT(*) FROM PIO_PROD_BAK_YYYYMMDD;
SELECT COUNT(*) FROM PIO_SCEN_BAK_YYYYMMDD;
SELECT COUNT(*) FROM PIO_CUST_BAK_YYYYMMDD;
SELECT COUNT(*) FROM PIO_CDET_BAK_YYYYMMDD;

-- Run each SELECT and use TOAD's Export Dataset -> CSV for an external copy.
SELECT * FROM PIO_PROD_BAK_YYYYMMDD ORDER BY SCENARIO_ID;
SELECT * FROM PIO_SCEN_BAK_YYYYMMDD ORDER BY SCENARIO_CODE;
SELECT * FROM PIO_CUST_BAK_YYYYMMDD ORDER BY AML_SCENARIO_CODE, SEQ;
SELECT * FROM PIO_CDET_BAK_YYYYMMDD ORDER BY AML_SCENARIO_CODE, SEQ;

